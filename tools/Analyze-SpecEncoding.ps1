$Utf8 = [System.Text.UTF8Encoding]::new($false)
$Path = Join-Path $PSScriptRoot '..\spec.md'
$Text = [System.IO.File]::ReadAllText($Path, $Utf8)

function Get-Hex([string]$S) {
    return (($Utf8.GetBytes($S) | ForEach-Object { '{0:X2}' -f $_ }) -join ' ')
}

$Candidates = @(
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC5, 0x93); Char = 0x201C }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0x9D); Char = 0x201D }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9C); Char = 0x2013 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9D); Char = 0x2014 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x84, 0xA2); Char = 0x2019 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0xA6); Char = 0x2026 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0x93); Char = 0x2013 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0x94); Char = 0x2014 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9C, 0xC2, 0x93); Char = 0x2013 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9C, 0xC2, 0x94); Char = 0x2014 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9D, 0xC2, 0x93); Char = 0x2014 }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC5, 0x93, 0xC2, 0x9D); Char = 0x201C }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC5, 0xBE); Char = 0x201C }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC5, 0xBE, 0xC2, 0x9D); Char = 0x201D }
    @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9C, 0xC2, 0xAC); Char = 0x2014 }
)

foreach ($C in ($Candidates | Sort-Object { $_.Bytes.Count } -Descending)) {
    $Old = $Utf8.GetString([byte[]]$C.Bytes)
    $Count = ([regex]::Matches($Text, [regex]::Escape($Old))).Count
    if ($Count -gt 0) {
        Write-Output ("{0}: U+{1:X4} hex={2}" -f $Count, $C.Char, (Get-Hex $Old))
    }
}

# Scan for any remaining C3 A2 E2 82 AC prefix sequences
$Prefix = $Utf8.GetString([byte[]]@(0xC3, 0xA2, 0xE2, 0x82, 0xAC))
Write-Output "Remaining euro-sign mojibake prefix count: $(([regex]::Matches($Text, [regex]::Escape($Prefix))).Count)"
