function Get-DefEnd($Start) {
    for ($i = $Start + 1; $i -lt $Lines.Count; $i++) {
        if ($Lines[$i] -match '^  [A-Za-z0-9_-]+:' -and $Lines[$i] -notmatch '^    ') { return $i }
    }
    return $Lines.Count
}

function Get-DefaultsInRange($Start, $End) {
    $results = @()
    $currentKey = $null
    for ($i = $Start; $i -lt $End; $i++) {
        $line = $Lines[$i]
        if ($line -match '^\s{4,8}([a-zA-Z0-9_]+):\s*$' -and $line -notmatch 'properties:|required:|enum:|type:|description:|allOf:|title:|items:|minimum:|maximum:|anyOf:|meta:') {
            $currentKey = $Matches[1]
        }
        if ($line -match '^\s+default:\s*(.*)$' -and $currentKey -and $currentKey -ne 'default') {
            $val = $Matches[1].Trim()
            if ($val -eq '' -or $val -eq '@') { $currentKey = $null; continue }
            $results += [PSCustomObject]@{ Key = $currentKey; Value = $val; Line = ($i + 1) }
            $currentKey = $null
        }
    }
    return $results
}

