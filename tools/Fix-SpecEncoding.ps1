# Fixes mojibake in Markdown spec files (multi-layer UTF-8 / CP1252 corruption).
$ErrorActionPreference = 'Stop'
$Utf8 = [System.Text.UTF8Encoding]::new($false)

function Get-StringFromUtf8Bytes([byte[]]$Bytes)
{
    return $Utf8.GetString($Bytes)
}

function Get-EncodingReplacements
{
    $Items = @(
        # Quadruple-layer mojibake (longest first)
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0xA0, 0xC3, 0x8B, 0xC5, 0x93); Char = 0x2198 }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xC3, 0xA2, 0xE2, 0x80, 0x9E, 0xC2, 0xA2); Char = 0x2019 }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xC3, 0x85, 0xE2, 0x80, 0x9C); Char = 0x201C }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xC3, 0x82, 0xC2, 0xA6); Char = 0x2026 }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xC3, 0x82, 0xC2, 0x9D); Char = 0x201D }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xE2, 0x80, 0x9D); Char = 0x2014 }
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x80, 0x9A, 0xC2, 0xAC, 0xE2, 0x80, 0x9C); Char = 0x2013 }
        @{ Bytes = @(0xC3, 0x83, 0xC6, 0x92, 0xC3, 0x82, 0xC2, 0xB6); Char = 0x00F6 }
        @{ Bytes = @(0xC3, 0x83, 0xC6, 0x92, 0xE2, 0x80, 0x94); Char = 0x00D7 }
        # Triple/double-layer mojibake
        @{ Bytes = @(0xC3, 0x83, 0xC2, 0xA2, 0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0xA0, 0xE2, 0x80, 0x99); Char = 0x2192 }
        @{ Bytes = @(0xC3, 0x83, 0xE2, 0x80, 0x9A, 0xC2, 0xA7); Char = 0x00A7 }
        @{ Bytes = @(0xC3, 0x82, 0xC2, 0xA7); Char = 0x00A7 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0xA0, 0xE2, 0x80, 0x99); Char = 0x2192 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x80, 0xA0, 0xE2, 0x80, 0x99); Char = 0x2192 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC5, 0x93); Char = 0x201C }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0x9D); Char = 0x201D }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9C); Char = 0x2013 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x80, 0x9D); Char = 0x2014 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xE2, 0x84, 0xA2); Char = 0x2019 }
        @{ Bytes = @(0xC3, 0xA2, 0xE2, 0x82, 0xAC, 0xC2, 0xA6); Char = 0x2026 }
        @{ Bytes = @(0xC3, 0x83, 0xE2, 0x80, 0x94); Char = 0x00D7 }
    )

    $Replacements = [ordered]@{}
    foreach ($Item in $Items)
    {
        $Key = Get-StringFromUtf8Bytes ([byte[]]$Item.Bytes)
        $Replacements[$Key] = [string][char]$Item.Char
    }

    return $Replacements
}

function Repair-MojibakeText
{
    param([string]$Content)

    $Replacements = Get-EncodingReplacements
    $TotalReplacements = 0
    $Changed = $true
    $Pass = 0

    while ($Changed -and $Pass -lt 8)
    {
        $Changed = $false
        $Pass++

        foreach ($Entry in $Replacements.GetEnumerator())
        {
            $Old = $Entry.Key
            $New = $Entry.Value
            $Count = ([regex]::Matches($Content, [regex]::Escape($Old))).Count
            if ($Count -gt 0)
            {
                $Content = $Content.Replace($Old, $New)
                $TotalReplacements += $Count
                $Changed = $true
                Write-Host ("  pass {0}: {1} x U+{2:X4} ({3} bytes)" -f $Pass, $Count, [int][char]$New, $Old.Length)
            }
        }
    }

    return [PSCustomObject]@{
        Content = $Content
        TotalReplacements = $TotalReplacements
        Passes = $Pass
    }
}

$TargetPaths = @(
    (Join-Path $PSScriptRoot '..\spec.md')
    (Join-Path $PSScriptRoot '..\docs\currentstatus.md')
)

foreach ($TargetPath in $TargetPaths)
{
    if (-not (Test-Path $TargetPath))
    {
        continue
    }

    $Original = [System.IO.File]::ReadAllText($TargetPath, $Utf8)
    Write-Host "Repairing: $TargetPath"
    $Result = Repair-MojibakeText -Content $Original

    if ($Result.Content -ne $Original)
    {
        [System.IO.File]::WriteAllText($TargetPath, $Result.Content, $Utf8)
        Write-Host ("Updated: {0} ({1} replacements in {2} pass(es))" -f $TargetPath, $Result.TotalReplacements, $Result.Passes)
    }
    else
    {
        Write-Host "No encoding changes needed: $TargetPath"
    }

    Write-Host ''
}
