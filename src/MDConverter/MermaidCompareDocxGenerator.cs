using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using MDConverter.Options;
using MermaidRecognition.Layout;
using MermaidRecognition.NaiadAdapter;
using MermaidSharp;

namespace MDConverter;

/// <summary>
/// One flowchart scenario for legacy vs native render comparison in DOCX.
/// </summary>
public sealed class MermaidCompareScenario
{
    public MermaidCompareScenario(string Title, string MermaidSource)
    {
        if (string.IsNullOrWhiteSpace(Title))
        {
            throw new ArgumentException("Title is required.", nameof(Title));
        }

        if (string.IsNullOrWhiteSpace(MermaidSource))
        {
            throw new ArgumentException("Mermaid source is required.", nameof(MermaidSource));
        }

        this.Title = Title;
        this.MermaidSource = MermaidSource;
    }

    public string Title { get; }

    public string MermaidSource { get; }
}

/// <summary>
/// Builds a DOCX document with side-by-side legacy Naiad and native Sugiyama PNG renders (pass 22).
/// </summary>
public static class MermaidCompareDocxGenerator
{
    /// <summary>
    /// Writes a comparison DOCX for the supplied scenarios.
    /// </summary>
    /// <param name="Scenarios">Flowchart scenarios to compare.</param>
    /// <param name="OutputDocxPath">Destination DOCX path.</param>
    /// <param name="WorkDirectory">Directory for intermediate PNG and markdown artefacts.</param>
    public static void Write(
        IReadOnlyList<MermaidCompareScenario> Scenarios,
        string OutputDocxPath,
        string WorkDirectory)
    {
        if (Scenarios == null || Scenarios.Count == 0)
        {
            throw new ArgumentException("At least one scenario is required.", nameof(Scenarios));
        }

        if (string.IsNullOrWhiteSpace(OutputDocxPath))
        {
            throw new ArgumentException("Output DOCX path is required.", nameof(OutputDocxPath));
        }

        string EffectiveWorkDirectory = string.IsNullOrWhiteSpace(WorkDirectory)
            ? Path.GetDirectoryName(Path.GetFullPath(OutputDocxPath)) ?? Environment.CurrentDirectory
            : WorkDirectory;

        Directory.CreateDirectory(EffectiveWorkDirectory);
        string MarkdownPath = Path.Combine(EffectiveWorkDirectory, "compare.generated.md");
        StringBuilder MarkdownBuilder = new StringBuilder();
        MarkdownBuilder.AppendLine("# Flowchart render comparison (legacy Naiad vs native Sugiyama)");
        MarkdownBuilder.AppendLine();
        MarkdownBuilder.AppendLine("Generated by NativeCompareDocx (pass 22 R1 slice). Each section shows the same Mermaid source rendered twice.");
        MarkdownBuilder.AppendLine();

        for (int Index = 0; Index < Scenarios.Count; Index++)
        {
            MermaidCompareScenario Scenario = Scenarios[Index];
            string Slug = Slugify(Scenario.Title);
            string LegacyPngName = Slug + "-legacy.png";
            string NativePngName = Slug + "-native.png";
            string LegacyPngPath = Path.Combine(EffectiveWorkDirectory, LegacyPngName);
            string NativePngPath = Path.Combine(EffectiveWorkDirectory, NativePngName);

            string LegacySvg = RenderLegacySvg(Scenario.MermaidSource);
            string NativeSvg = RenderNativeSvg(Scenario.MermaidSource);

            byte[]? LegacyPng = MermaidDiagramExport.TryRasterizeSvg(LegacySvg);
            byte[]? NativePng = MermaidDiagramExport.TryRasterizeSvg(NativeSvg);

            if (LegacyPng == null || LegacyPng.Length == 0)
            {
                throw new MarkdownToDocxException("Legacy PNG rasterisation failed for scenario: " + Scenario.Title);
            }

            if (NativePng == null || NativePng.Length == 0)
            {
                throw new MarkdownToDocxException("Native PNG rasterisation failed for scenario: " + Scenario.Title);
            }

            File.WriteAllBytes(LegacyPngPath, LegacyPng);
            File.WriteAllBytes(NativePngPath, NativePng);

            MarkdownBuilder.AppendLine("## " + Scenario.Title);
            MarkdownBuilder.AppendLine();
            MarkdownBuilder.AppendLine("```mermaid");
            MarkdownBuilder.AppendLine(NormalizeMermaidBody(Scenario.MermaidSource));
            MarkdownBuilder.AppendLine("```");
            MarkdownBuilder.AppendLine();
            MarkdownBuilder.AppendLine("### Legacy (Naiad)");
            MarkdownBuilder.AppendLine();
            MarkdownBuilder.AppendLine("![Legacy Naiad render](");
            MarkdownBuilder.Append(LegacyPngName);
            MarkdownBuilder.AppendLine(")");
            MarkdownBuilder.AppendLine();
            MarkdownBuilder.AppendLine("### Native (Sugiyama / MSAGL)");
            MarkdownBuilder.AppendLine();
            MarkdownBuilder.AppendLine("![Native Sugiyama render](");
            MarkdownBuilder.Append(NativePngName);
            MarkdownBuilder.AppendLine(")");
            MarkdownBuilder.AppendLine();
        }

        File.WriteAllText(MarkdownPath, MarkdownBuilder.ToString(), new UTF8Encoding(false));

        MarkdownToDocxOptions Options = new MarkdownToDocxOptions
        {
            Images = new ImageOptions
            {
                MaxWidthCm = 14.5,
                ScaleDownOnly = true
            }
        };

        MarkdownToDocxConverter Converter = new MarkdownToDocxConverter(Options);
        Converter.ConvertFile(MarkdownPath, OutputDocxPath);
    }

    private static string RenderLegacySvg(string MermaidSource)
    {
        RenderOptions Options = RenderOptions.Default;
        if (FlowchartRecognitionRenderBridge.TryRenderLegacyNaiadFlowchartSvg(MermaidSource, Options, out string RecognitionSvg))
        {
            return RecognitionSvg;
        }

        return Mermaid.Render(MermaidSource, Options);
    }

    private static string RenderNativeSvg(string MermaidSource)
    {
        if (!NativeFlowchartRenderBridge.TryRenderFlowchartSvg(MermaidSource, out string Svg))
        {
            throw new MarkdownToDocxException("Native Sugiyama render failed.");
        }

        return Svg;
    }

    private static string NormalizeMermaidBody(string MermaidSource) => (MermaidSource ?? string.Empty).Replace("\r\n", "\n").Replace('\r', '\n').TrimEnd('\n');

    private static string Slugify(string Title)
    {
        if (string.IsNullOrWhiteSpace(Title))
        {
            return "scenario";
        }

        StringBuilder Builder = new StringBuilder();
        foreach (char Character in Title)
        {
            if (char.IsLetterOrDigit(Character))
            {
                Builder.Append(char.ToLowerInvariant(Character));
            }
            else if (Character == ' ' || Character == '-' || Character == '_')
            {
                if (Builder.Length > 0 && Builder[Builder.Length - 1] != '-')
                {
                    Builder.Append('-');
                }
            }
        }

        string Slug = Builder.ToString().Trim('-');
        if (string.IsNullOrEmpty(Slug))
        {
            Slug = "scenario";
        }

        return Slug;
    }
}
